const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktopChat', {
  open: id => ipcRenderer.invoke('chat:open', id),
  clear: () => ipcRenderer.invoke('chat:clear'),
  multiChat: (action,id,channel) => ipcRenderer.invoke('multi:chat',action,id,channel),
  multiBounds: (id,bounds) => ipcRenderer.send('multi:bounds',id,bounds),
  bounds: bounds => ipcRenderer.send('chat:bounds', bounds),
  reload: () => ipcRenderer.send('chat:reload'),
  login: () => ipcRenderer.send('chat:login'),
  account: () => ipcRenderer.invoke('chat:account'),
  homeSettings: value => ipcRenderer.invoke('home:settings',value),
  following: () => ipcRenderer.invoke('chat:following'),
  lastAddress: () => ipcRenderer.invoke('settings:last-address'),
  viewingState: () => ipcRenderer.invoke('settings:viewing-state'),
  saveViewingState: state => ipcRenderer.sendSync('settings:save-viewing-state', state),
  saveAddress: address => ipcRenderer.send('settings:save-address', address),
  playerMode: enabled => ipcRenderer.invoke('player:mode', enabled),
  pip: config => ipcRenderer.invoke('player:pip', config),
  closePiP: () => ipcRenderer.send('player:pip-close'),
  onPiP: callback => ipcRenderer.on('player:pip-state', (_event, active) => callback(active)),
  captureState: () => ipcRenderer.invoke('capture:state'),
  captionState: () => ipcRenderer.invoke('caption:state'),
  captionPosition: () => ipcRenderer.invoke('caption:position'),
  captionSetPosition: value => ipcRenderer.invoke('caption:set-position',value),
  captionStart: (model,device,language) => ipcRenderer.invoke('caption:start', model,device,language),
  captionStop: () => ipcRenderer.invoke('caption:stop'),
  captionAudio: data => ipcRenderer.send('caption:audio',data),
  captionReset: epoch => ipcRenderer.send('caption:reset',epoch),
  captionVod: config => ipcRenderer.invoke('caption:vod',config),
  captionLive: config => ipcRenderer.invoke('caption:live',config),
  onCaptionState: callback => ipcRenderer.on('caption:state',(_event,state)=>callback(state)),
  onCaptionResult: callback => ipcRenderer.on('caption:result',(_event,result)=>callback(result)),
  downloadState: () => ipcRenderer.invoke('vod:download-state'),
  download: (action, config) => ipcRenderer.invoke('vod:download', action, config),
  onDownload: callback => ipcRenderer.on('vod:download-state', (_event, state) => callback(state)),
  capture: (action, config) => ipcRenderer.invoke('capture:command', action, config),
  capturePlayhead: epoch => ipcRenderer.send('capture:playhead', epoch),
  onCapture: callback => ipcRenderer.on('capture:state', (_event, state) => callback(state)),
  logout: () => ipcRenderer.invoke('chat:logout'),
  onAccount: callback => ipcRenderer.on('chat:account', (_event, state) => callback(state)),
  popout: action => ipcRenderer.invoke('chat:popout',action),
  onChatPopout: callback => ipcRenderer.on('chat:popout-state',(_event,state)=>callback(state)),
  onStatus: callback => ipcRenderer.on('chat:status', (_event, text) => callback(text))
});
